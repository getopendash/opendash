/**
 * By exact name only, never a prefix: MySQL resolves a name that isn't a built-in to a stored function in the default
 * database, so `st_peek()` would run one. Spatial functions aren't in the list: refused, until named here one by one.
 */
export const isMySqlFunction = (name: string) => MYSQL_FUNCTIONS.has(name);
