// Writes src/runtime.generated.ts: the frame runtime (React, ECharts, the kit, the bridge, the lockdown and the
// theme) as one script and its hash, so the web app serves it without building anything. Run after changing anything
// in src/runtime: `pnpm --filter @opendash/apps build:runtime`. test/runtime.test.ts fails while it's out of date.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildRuntime } from "../src/check/runtime";

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/runtime.generated.ts");
const built = await buildRuntime();
writeFileSync(
  out,
  `// Generated by packages/apps/scripts/build-runtime.ts. Do not edit; run \`pnpm --filter @opendash/apps build:runtime\`.\n` +
    `export const RUNTIME_HASH = ${JSON.stringify(built.hash)};\n` +
    `export const RUNTIME_JS = ${JSON.stringify(built.js)};\n`,
);
console.log(`runtime ${built.hash}: ${built.bytes} bytes`);
